-- entries に馬体重と前走からの増減を足す。
--
-- 根拠は docs/data-model.md の entries。
--
-- 理由: 2026年札幌記念を予想したときに、馬体重を残す先が無かった。16頭のうち複数の馬で
-- 陣営が馬体重に言及していて（サクラファレルの「12日調教後の馬体重は524キロ」、
-- マイネルモーントの「460〜470キロで出せれば」）、仕上がりを判断する材料として実際に
-- 使われている。馬を読む役からも、9歳馬の状態を見る材料が持てないという指摘が上がった。
--
-- どちらも null 可にする。馬体重が発表されるのは当日で、枠順確定時には存在しない。
-- 登録は結果の取り込みと一緒に行うので、それまで空のままになる。過去の出走を後から
-- 登録するときも、情報源によっては取れない。
--
-- 増減を別の列で持つのは、前走が DB に無いのが常態だから。docs/agent-design.md で
-- 「過去のレースは、読むと決めた出走だけを登録する」と決めているため、前走の馬体重が
-- DB に入っていないことの方が多く、増減を引き算では出せない。導出値ではなく、情報源が
-- そのまま出している別の事実として扱う。
--
-- 増減には CHECK を付けない。減っている場合は負の値になる。null は「増減が0」ではなく、
-- 前走比が発表されない場合と取れなかった場合の両方を指す。
--
-- カラム追加なので、decisions/0004 に従い Neon のブランチは切らない。

ALTER TABLE entries ADD COLUMN body_weight integer;
ALTER TABLE entries ADD COLUMN body_weight_diff integer;

ALTER TABLE entries ADD CONSTRAINT entries_body_weight_check CHECK (body_weight > 0);
