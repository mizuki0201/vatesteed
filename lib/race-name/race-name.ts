/**
 * レース名の正規化。
 *
 * `races.race_name` はただのテキストなので、1文字でも違うと別のレースとして扱われる。
 * 別名マスタも「春天 → 正式名称」を引く仕組みである以上、引き先が1つに決まっていないと
 * 成立しない。そのため揺れうる箇所の文字種を固定する（docs/data-model.md#表記ルール）。
 *
 * **JRA 公式サイトのレース名は全角括弧で書かれている。** 公式ページから写すと全角が
 * 混ざるので、登録の前に必ずここを通す。
 *
 * 別名マスタ（「春天」→「天皇賞(春)」）を作るときは、同じディレクトリに足す。
 */

/**
 * 表記ルールに沿って正規化する。
 *
 * | 項目 | ルール | 例 |
 * | --- | --- | --- |
 * | 括弧 | 半角 `( )` | `天皇賞（春）` → `天皇賞(春)` |
 * | 数字 | 半角 | `２歳ステークス` → `2歳ステークス` |
 * | 英字 | 半角 | `ＮＨＫマイルカップ` → `NHKマイルカップ` |
 * | 空白 | 入れない | `天皇賞 (春)` → `天皇賞(春)` |
 *
 * 実体は Unicode の NFKC 正規化ひとつで足りる。全角の括弧・数字・英字を半角へ寄せるのも、
 * 半角カナを全角へ寄せる（濁点の合成を含む）のも、まとめて面倒を見てくれる。
 * 文字種ごとに置換表を書くと漏れるので使わない。
 *
 * **略称は展開しない。** `ホープフルS` → `ホープフルステークス` のような変換は
 * 1対1では決まらないので、エージェント側の別名マスタの仕事になる（マスタは未作成）。
 */
export function normalizeRaceName(name: string): string {
  return name.normalize("NFKC").replace(/\s+/g, "");
}
